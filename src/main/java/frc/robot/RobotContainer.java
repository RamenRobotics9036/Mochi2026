/**
 * The RobotContainer class is where the bulk of the robot structure is declared.
 *
 * <p>This class centralizes the hardware instances, UI device bindings, and
 * the mapping between operator inputs and subsystem commands for the 2026 season.
 */
public class RobotContainer {

    /** Maximum linear velocity of the robot in meters per second. */
    private double MaxSpeed = TunerConstants.kSpeedAt12Volts.in(MetersPerSecond);
    /** Maximum angular velocity of the robot in radians per second. */
    private double MaxAngularRate = RotationsPerSecond.of(0.75).in(RadiansPerSecond);

    /** Maximum linear velocity of the robot DURING TELEOP in meters per second. */
    private double TeleoperatedSpeed = Math.min(TunerConstants.kSpeedInTeleop.in(MetersPerSecond), MaxSpeed);

    /** Standard field-centric swerve request. Uses Velocity control for smoother movement.
     *  Small deadband catches residual near-zero commands from the slew limiter;
     *  main joystick deadband is handled by DriveSmooth. */
    private final SwerveRequest.FieldCentric drive = new SwerveRequest.FieldCentric()
            .withDeadband(0.02 * TeleoperatedSpeed)
            .withRotationalDeadband(0.02 * MaxAngularRate)
            .withDriveRequestType(DriveRequestType.Velocity);

    /** Brake request: Forces all modules into an X-pattern to resist movement. */
    private final SwerveRequest.SwerveDriveBrake brake = new SwerveRequest.SwerveDriveBrake();
    /** Point request: Orients all modules toward a specific direction without driving. */
    private final SwerveRequest.PointWheelsAt point = new SwerveRequest.PointWheelsAt();

    /** Telemetry helper for logging drivetrain state to AdvantageScope/Dashboard. */
    private final Telemetry logger = new Telemetry(MaxSpeed);

    /** Primary driver controller (Port 0). */
    private final CommandXboxController driveController = new CommandXboxController(0);
    /** Primary operator controller (Port 1). */
    private final CommandXboxController operateController = new CommandXboxController(1);

    /** Joystick processing pipeline: deadband + response curve + slew-rate limiting. */
    private final DriveSmooth m_driveSmooth = new DriveSmooth();

    /** The drivetrain subsystem, initialized using constants generated by Tuner X. */
    public final CommandSwerveDrivetrain drivetrain = TunerConstants.createDrivetrain();

    public final BasicInfoDashboard basicInfoDashboard = new BasicInfoDashboard(drivetrain);

    /** Field2d for Glass/SmartDashboard visualization. */
    public final Field2d m_glassField = new Field2d();

    /** Simulation wrapper - null when not in simulation. */
    public final SimWrapper m_simWrapper;
    public final ShowVisionOnField m_showVisionOnField;

    /** Pose of the blue tape on the field, or empty to hide. */
    public Optional<Pose2d> m_blueTapePose = Optional.of(new Pose2d(1.0, 1.0, new Rotation2d()));

    /** Pose of the red tape on the field, or empty to hide. */
    public Optional<Pose2d> m_redTapePose = Optional.of(new Pose2d(2.0, 1.0, new Rotation2d()));

    public final LimelightOdometry m_limelightOdometry;

    public final ShooterSubsystem shooterSubsystem = new ShooterSubsystem();

    /** Vision-only Kalman filter for precise stationary position estimation. */
    public final VisionKalmanFilter m_visionKalmanFilter = new VisionKalmanFilter();

    /** Tracks whether the robot is motionless and for how long. */
    public final MotionlessTracker m_motionlessTracker;

    /**
     * Constructs the RobotContainer.
     * Initializes autonomous selection dashboards and binds controller inputs to commands.
     */
    public RobotContainer() {
        Field2d debugField = null;

        SmartDashboard.putData("GlassField", m_glassField);

        AutoLogic.initShuffleboard(drivetrain);
        configureBindings();

        // $VISIONSIM - Wrapper for sim features
        if (Robot.isSimulation()) {
            m_simWrapper = new SimWrapper(
                drivetrain,
                this::resetRobotPose);

            debugField = m_simWrapper.getSimDebugField();
        }
        else {
            m_simWrapper = null;
        }

        m_showVisionOnField = new ShowVisionOnField(
            m_glassField, debugField);

        // Setup vision system
        drivetrain.setVisionEnabledSupplier(basicInfoDashboard::isVisionEnabled);

        m_motionlessTracker = new MotionlessTracker(() -> drivetrain.getState().Speeds);
        m_motionlessTracker.setOnStartedMoving(m_visionKalmanFilter::reset);

        m_limelightOdometry = new LimelightOdometry(drivetrain::addVisionMeasurement);
        m_limelightOdometry.setVisionKalmanFilter(m_visionKalmanFilter, m_motionlessTracker::isMotionless);

        basicInfoDashboard.setVisionConfidenceSupplier(
            m_limelightOdometry::getCurrentConfidenceScore);
        basicInfoDashboard.setNumLockedTagsSupplier(
            m_limelightOdometry::getNumLockedTags);
        basicInfoDashboard.setTxSupplier(
            m_limelightOdometry::getTx);
        basicInfoDashboard.setTargetListSupplier(
            m_limelightOdometry::getTargetList);

        basicInfoDashboard.setVisionKalmanSupplier(() -> m_visionKalmanFilter);
        basicInfoDashboard.setIsRobotMotionlessSupplier(m_motionlessTracker::isMotionless);
        basicInfoDashboard.setSecondsStillSupplier(m_motionlessTracker::getSecondsStill);
    }

    /**
     * Processes raw joystick input for translation (X-axis).
     * Pipeline: deadband+rescale → response curve → slew-rate limit → speed scale.
     *
     * @return Scaled velocity in meters per second.
     */
    private double getDriveX() {
        double input = m_driveSmooth.processTranslationX(-driveController.getLeftY());
        // Reduce speed by 50% if the Right Bumper is held for fine positioning
        double inputScale = driveController.rightBumper().getAsBoolean() ? 0.5 : 1.0;
        return input * TeleoperatedSpeed * inputScale;
    }

    /**
     * Processes raw joystick input for translation (Y-axis).
     * Pipeline: deadband+rescale → response curve → slew-rate limit → speed scale.
     *
     * @return Scaled velocity in meters per second.
     */
    private double getDriveY() {
        double input = m_driveSmooth.processTranslationY(-driveController.getLeftX());
        double inputScale = driveController.rightBumper().getAsBoolean() ? 0.5 : 1.0;
        return input * TeleoperatedSpeed * inputScale;
    }

    /**
     * Processes raw joystick input for rotation.
     * Pipeline: deadband+rescale → response curve → slew-rate limit → speed scale.
     *
     * @return Scaled angular velocity in radians per second.
     */
    private double getDriveRotate() {
        double input = m_driveSmooth.processRotation(-driveController.getRightX());
        double inputScale = driveController.rightBumper().getAsBoolean() ? 0.5 : 1.0;
        return input * MaxAngularRate * inputScale;
    }

    /**
     * Defines trigger-to-command mappings.
     */
    private void configureBindings() {
        // Set the default command for the drivetrain to follow joystick inputs continuously
        drivetrain.setDefaultCommand(
            drivetrain.applyRequest(() -> {
                double leftX = getDriveX();
                double leftY = getDriveY();
                double rightX = getDriveRotate();

                // $VISIONSIM - Wrapper for sim features
                if (Robot.isSimulation()) {
                    JoystickInputsRecord newJoystickInputs =

                        SimWrapper.transformJoystickOrientation(
                        drivetrain.getOperatorForwardDirection().getDegrees(),
                        leftX,
                        leftY,
                        rightX);
                    leftX = -newJoystickInputs.driveX();
                    leftY =- newJoystickInputs.driveY();
                    rightX = newJoystickInputs.rotatetX();
                }

                return drive.withVelocityX(leftX)
                     .withVelocityY(leftY)
                     .withRotationalRate(rightX);
            })
        );

        //shooterSubsystem.setDefaultCommand(new ShooterTestCommand(shooterSubsystem, operateController));

        // Keep the drivetrain in an Idle state while the robot is disabled
        final var idle = new SwerveRequest.Idle();
        RobotModeTriggers.disabled().whileTrue(
            drivetrain.applyRequest(() -> idle).ignoringDisable(true)
        );

        // Map Button A to the brake command for defensive positioning
        driveController.a().whileTrue(drivetrain.applyRequest(() -> brake));

        // Map Button B to orient wheels based on the left joystick angle (useful for testing)
        driveController.b().whileTrue(drivetrain.applyRequest(() ->
            point.withModuleDirection(new Rotation2d(-driveController.getLeftY(), -driveController.getLeftX()))
        ));

        // SysId Characterization bindings (Back/Start + X/Y) for automated PID tuning
        driveController.back().and(driveController.y()).whileTrue(drivetrain.sysIdDynamic(Direction.kForward));
        driveController.back().and(driveController.x()).whileTrue(drivetrain.sysIdDynamic(Direction.kReverse));
        driveController.start().and(driveController.y()).whileTrue(drivetrain.sysIdQuasistatic(Direction.kForward));
        driveController.start().and(driveController.x()).whileTrue(drivetrain.sysIdQuasistatic(Direction.kReverse));

        // Recalibrate the gyro's forward heading using the Left Bumper
        driveController.leftBumper().onTrue(drivetrain.runOnce(() -> drivetrain.seedFieldCentric()));

        // $VISIONSIM - POV buttons for sim
        if (Robot.isSimulation()) {
            // In simulation, inject drift with POV right to test vision correction
            driveController.povRight()
                .onTrue(drivetrain.runOnce(() -> m_simWrapper.injectDrift(0.5, 15.0)));

            // POV left resets robot to the starting pose of the selected auto
            driveController.povLeft().onTrue(
                drivetrain
                    .runOnce(() -> m_simWrapper.cycleResetPosition(AutoLogic.getSelectedAutoStartingPose())));
        }

        // Hook up the telemetry logger to the drivetrain periodic updates
        drivetrain.registerTelemetry(logger::telemeterize);

        // Y button: tape-drop auto sequence
        // Checks Kalman convergence, drops blue tape, runs auto, drops red tape
        driveController.y().onTrue(createTapeDropAutoCommand());
    }

    /**
     * Wrapper for team-specific commands to handle simulation behavior.
     *
     * @param command The command to wrap.
     * @return The original command or an empty command if in simulation.
     */
    private Command CmdWrapperTeamCommand(Command command) {
        if (RobotBase.isSimulation()) {
            return Commands.none();
        }
        return command;
    }

    /**
     * Computes a tape pose at the front of the robot, parallel to the front face.
     * The tape is placed just beyond the front edge so it doesn't overlap the robot.
     *
     * @param robotPose The robot's current pose
     * @return The tape Pose2d positioned in front of the robot
     */
    private Pose2d computeFrontTapePose(Pose2d robotPose) {
        // Half the bumper length (center to front edge): 0.864m / 2 = 0.432m
        // Then push out by the tape width so it doesn't overlap the bumpers
        double halfBumperLength = 0.864 / 2.0;
        double tapeWidth = 0.137;
        double frontOffset = halfBumperLength + (tapeWidth / 2);

        // Transform to place tape in front of the robot, rotated 90° so the
        // tape's long axis is parallel to the robot's front face
        return robotPose.transformBy(
            new Transform2d(frontOffset, 0, Rotation2d.fromDegrees(90)));
    }

    /**
     * Creates a command sequence that:
     * 1) Checks Kalman filter convergence (aborts if not converged)
     * 2) Drops blue tape at the front of the auto starting pose
     * 3) Runs the currently selected auto
     * 4) Drops red tape at the front of the robot
     *
     * @return The composed command
     */
    private Command createTapeDropAutoCommand() {
        return Commands.either(
            // Converged path: clear tape, drop blue tape, pause, run auto, drop red tape
            Commands.sequence(
                Commands.runOnce(this::clearTape),
                Commands.runOnce(() -> {
                    Pose2d kalmanPose = m_visionKalmanFilter.getEstimate();
                    m_blueTapePose = Optional.of(computeFrontTapePose(kalmanPose));
                    System.out.println("Blue tape dropped at Kalman estimate: " + m_blueTapePose.get());
                }),
                Commands.waitSeconds(1.0),
                AutoLogic.getSelectedAutoCommand(),
                Commands.runOnce(() -> {
                    Pose2d currentPose = drivetrain.getState().Pose;
                    m_redTapePose = Optional.of(computeFrontTapePose(currentPose));
                    System.out.println("Red tape dropped at: " + m_redTapePose.get());
                })
            ),
            // Not converged path: print warning and do nothing
            Commands.runOnce(() ->
                System.out.println("Kalman filter not converged — tape drop auto aborted")),
            // Condition: is the Kalman filter converged?
            m_visionKalmanFilter::hasConverged
        );
    }

    /**
     * Retrieves the autonomous routine selected via the dashboard at the start of the match.
     *
     * @return The command to execute during the autonomous period.
     */
    public Command getAutonomousCommand() {
        return AutoLogic.getSelectedAutoCommand();
    }

    /**
     * Clears both tape poses so they are no longer displayed on the field.
     */
    private void clearTape() {
        m_blueTapePose = Optional.empty();
        m_redTapePose = Optional.empty();
    }

    /**
     * Called when the robot pose is reset in simulation.
     * This is triggered by GroundTruthSim via the consumer pattern.
     *
     * <p>Resets both the ground truth pose and the drivetrain pose to the specified pose.
     * Also resets the vision system simulation pose history if a Vision instance is set.
     *
     * @param pose The new pose the robot has been reset to
     */
    private void resetRobotPose(Pose2d pose) {
        System.out.println("Robot pose reset to: " + pose);

        drivetrain.resetPose(pose);

        // $VISIONSIM - Clean reset
        if (Robot.isSimulation()) {
            // NOTE: This is only reset in simulation since m_simWrapper isnt ever
            // instantiated in real mode.  This is because the pose we reset
            // here is the ground truth pose which is only relevent in simulation.
            m_simWrapper.resetSimPose(pose);
        }

        // Reset the vision-only Kalman filter
        m_visionKalmanFilter.reset();

        // Remove any tape from the field
        clearTape();
    }
}
